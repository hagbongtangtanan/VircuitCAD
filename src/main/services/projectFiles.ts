import { readFile, writeFile } from 'node:fs/promises'
import {
  parseProjectText,
  parseSketchText,
  openKindForPath,
  serializeProject,
  ProjectFileError,
  type OpenFileResult,
  type ProjectFile,
} from '../../shared/project'

/**
 * File-system side of opening and saving. Electron-free so the round-trip can
 * be tested against a temporary directory; the IPC layer owns the dialogs.
 */

const MAX_FILE_BYTES = 4 * 1024 * 1024
const MAX_PNG_BYTES = 32 * 1024 * 1024
const MAX_PDF_BYTES = 48 * 1024 * 1024
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])
const PDF_SIGNATURE = Buffer.from('%PDF-', 'ascii')
const PNG_DATA_URL = /^data:image\/png;base64,([A-Za-z0-9+/=]+)$/
const PDF_BASE64 = /^[A-Za-z0-9+/=]+$/

async function readText(path: string): Promise<string> {
  const buffer = await readFile(path)
  if (buffer.byteLength > MAX_FILE_BYTES) {
    throw new ProjectFileError('The file is too large to open.')
  }
  return buffer.toString('utf8')
}

export async function readProjectFile(path: string): Promise<ProjectFile> {
  return parseProjectText(await readText(path))
}

export async function writeProjectFile(path: string, project: ProjectFile): Promise<void> {
  await writeFile(path, serializeProject(project), 'utf8')
}

/** Reads either a project or a plain `.ino` sketch, based on the extension. */
export async function openFile(path: string): Promise<OpenFileResult> {
  const kind = openKindForPath(path)
  if (kind === null) {
    throw new ProjectFileError('Open a VircuitCAD (.vcc) project or an .ino sketch.')
  }

  const text = await readText(path)
  if (kind === 'sketch') {
    return { kind, path, sketch: parseSketchText(text) }
  }
  return { kind, path, project: parseProjectText(text) }
}

export async function writeSketchFile(path: string, sketch: string): Promise<void> {
  await writeFile(path, parseSketchText(sketch), 'utf8')
}

/** Writes a PNG captured by the renderer. The data URL is validated here, not trusted. */
export async function writePngFile(path: string, dataUrl: string): Promise<void> {
  const payload = PNG_DATA_URL.exec(dataUrl)?.[1]
  if (payload === undefined) {
    throw new ProjectFileError('The image data is not a PNG.')
  }

  const buffer = Buffer.from(payload, 'base64')
  if (buffer.byteLength > MAX_PNG_BYTES) {
    throw new ProjectFileError('The image is too large to export.')
  }
  if (buffer.byteLength < PNG_SIGNATURE.length || !buffer.subarray(0, 8).equals(PNG_SIGNATURE)) {
    throw new ProjectFileError('The image data is not a PNG.')
  }

  await writeFile(path, buffer)
}

/** Writes a vector PDF generated by the renderer. */
export async function writePdfFile(path: string, base64: string): Promise<void> {
  if (!PDF_BASE64.test(base64)) {
    throw new ProjectFileError('The document data is not a PDF.')
  }

  const buffer = Buffer.from(base64, 'base64')
  if (buffer.byteLength > MAX_PDF_BYTES) {
    throw new ProjectFileError('The document is too large to export.')
  }
  if (buffer.byteLength < PDF_SIGNATURE.length || !buffer.subarray(0, 5).equals(PDF_SIGNATURE)) {
    throw new ProjectFileError('The document data is not a PDF.')
  }

  await writeFile(path, buffer)
}

export async function writeHexFile(path: string, hex: string): Promise<void> {
  if (hex.length > MAX_FILE_BYTES || !hex.startsWith(':')) {
    throw new ProjectFileError('There is no compiled HEX to export.')
  }
  await writeFile(path, hex.endsWith('\n') ? hex : `${hex}\n`, 'utf8')
}
